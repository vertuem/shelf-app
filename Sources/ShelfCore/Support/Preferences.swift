import Foundation

/// Every setting Shelf persists, with its default.
///
/// All settings live in `UserDefaults` under the app's own domain; nothing
/// syncs. The SwiftUI settings panes bind to the same keys with `@AppStorage`,
/// and the capture and paste paths read them through `Preferences` on every
/// use, so a change applies to the next copy without any notification.
public enum PrefKey {
    // General
    public static let showInMenuBar = "showInMenuBar"
    public static let shelfPosition = "shelfPosition"
    public static let cardColors = "cardColors"
    public static let copySound = "copySound"
    public static let pasteSound = "pasteSound"
    public static let pasteMode = "pasteMode"
    public static let restorePreviousClipboard = "restorePreviousClipboard"
    public static let alwaysPastePlainText = "alwaysPastePlainText"
    public static let keepHistory = "keepHistory"
    public static let manualPasteApps = "manualPasteApps"

    // Privacy
    public static let showDuringScreenSharing = "showDuringScreenSharing"
    public static let generateLinkPreviews = "generateLinkPreviews"
    public static let recognizeTextInImages = "recognizeTextInImages"
    public static let ignoreConfidential = "ignoreConfidential"
    public static let ignoreTransient = "ignoreTransient"
    public static let ignoreAutoGenerated = "ignoreAutoGenerated"
    public static let captureWhileLocked = "captureWhileLocked"
    public static let maxItemMegabytes = "maxItemMegabytes"
    public static let ignoredApps = "ignoredApps"
    public static let encryptAtRest = "encryptAtRest"
    public static let detectSecrets = "detectSecrets"

    // Shortcuts (hotkeys themselves are stored by KeyboardShortcuts)
    public static let quickPasteModifier = "quickPasteModifier"
    public static let plainTextModifier = "plainTextModifier"

    // About and updates
    public static let checkForUpdates = "checkForUpdates"
    public static let includeBetas = "includeBetas"
    public static let stabilityBuffer = "stabilityBuffer"
    public static let skippedVersion = "skippedVersion"
    public static let lastUpdateCheck = "lastUpdateCheck"

    // State
    public static let onboardingCompleted = "onboardingCompleted"
    public static let pausedUntil = "pausedUntil"
    public static let maccyImportOffered = "maccyImportOffered"
    public static let loginItemRegistered = "loginItemRegistered"
    public static let lastRetentionRun = "lastRetentionRun"
    public static let previousBundlePath = "previousBundlePath"
    public static let launchesSinceUpdate = "launchesSinceUpdate"
}

/// Where a card header's color comes from.
public enum CardColorMode: String, Sendable, CaseIterable {
    /// The source app's icon color.
    case app
    /// One color per content type: text blue, links green, and so on.
    case type
}

/// Shelf's own sounds, synthesized by `Scripts/generate-sounds.swift`.
public enum SoundEffect: String, Sendable, CaseIterable {
    case copy, paste

    /// The file name in the app bundle, without the extension.
    public var resourceName: String {
        switch self {
        case .copy: "Copy"
        case .paste: "Paste"
        }
    }
}

/// Where the shelf appears. Bottom and center lay cards out horizontally;
/// left and right stand them in a column along the screen edge.
public enum ShelfPosition: String, Sendable, CaseIterable {
    case bottom, left, right, center
}

public enum PasteMode: String, Sendable, CaseIterable {
    case toActiveApp
    case toClipboard
}

public enum QuickPasteModifier: String, Sendable, CaseIterable {
    case command, option, control
}

public enum PlainTextModifier: String, Sendable, CaseIterable {
    case shift, option
}

