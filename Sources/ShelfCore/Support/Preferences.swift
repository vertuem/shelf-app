/// Typed, thread-safe access to the settings for code outside SwiftUI views.
public struct Preferences: @unchecked Sendable {
    // UserDefaults is documented as thread-safe.
    public let defaults: UserDefaults

    public init(defaults: UserDefaults = .standard) {
        self.defaults = defaults
        defaults.register(defaults: Self.registrationDefaults)
    }

    public static var registrationDefaults: [String: Any] { [
        PrefKey.showInMenuBar: false,
        PrefKey.shelfPosition: ShelfPosition.bottom.rawValue,
        PrefKey.cardColors: CardColorMode.app.rawValue,
        PrefKey.copySound: false,
        PrefKey.pasteSound: true,
        PrefKey.pasteMode: PasteMode.toActiveApp.rawValue,
        PrefKey.restorePreviousClipboard: false,
        PrefKey.alwaysPastePlainText: false,
        PrefKey.keepHistory: RetentionPeriod.month.rawValue,
        PrefKey.manualPasteApps: Seeds.manualPasteApps,
        PrefKey.showDuringScreenSharing: false,
        PrefKey.generateLinkPreviews: false,
        PrefKey.recognizeTextInImages: true,
        PrefKey.ignoreConfidential: true,
        PrefKey.ignoreTransient: true,
        PrefKey.ignoreAutoGenerated: true,
        PrefKey.captureWhileLocked: false,
        PrefKey.maxItemMegabytes: 10,
        PrefKey.ignoredApps: Seeds.ignoredApps,
        PrefKey.encryptAtRest: true,
        PrefKey.detectSecrets: false,
        PrefKey.quickPasteModifier: QuickPasteModifier.command.rawValue,
        PrefKey.plainTextModifier: PlainTextModifier.shift.rawValue,
        PrefKey.checkForUpdates: true,
        PrefKey.includeBetas: false,
        PrefKey.stabilityBuffer: true,
        PrefKey.onboardingCompleted: false,
    ] }

    public var pasteMode: PasteMode {
        get { PasteMode(rawValue: defaults.string(forKey: PrefKey.pasteMode) ?? "") ?? .toActiveApp }
        nonmutating set { defaults.set(newValue.rawValue, forKey: PrefKey.pasteMode) }
    }

    public var shelfPosition: ShelfPosition {
        get { ShelfPosition(rawValue: defaults.string(forKey: PrefKey.shelfPosition) ?? "") ?? .bottom }
        nonmutating set { defaults.set(newValue.rawValue, forKey: PrefKey.shelfPosition) }
    }

    public var showInMenuBar: Bool { defaults.bool(forKey: PrefKey.showInMenuBar) }
    public var restorePreviousClipboard: Bool { defaults.bool(forKey: PrefKey.restorePreviousClipboard) }
    public var alwaysPastePlainText: Bool { defaults.bool(forKey: PrefKey.alwaysPastePlainText) }
    /// A tick when something you copy is saved. Off by default: it fires on every copy.
    public var copySound: Bool { defaults.bool(forKey: PrefKey.copySound) }
    /// A pop when a card is pasted or copied from the shelf, and the shelf's pin and remove sounds.
    public var pasteSound: Bool { defaults.bool(forKey: PrefKey.pasteSound) }

    public var keepHistory: RetentionPeriod {
        RetentionPeriod(rawValue: defaults.string(forKey: PrefKey.keepHistory) ?? "") ?? .month
    }

    public var manualPasteApps: Set<String> {
        Set(defaults.stringArray(forKey: PrefKey.manualPasteApps) ?? [])
    }

    public var showDuringScreenSharing: Bool { defaults.bool(forKey: PrefKey.showDuringScreenSharing) }
    public var generateLinkPreviews: Bool { defaults.bool(forKey: PrefKey.generateLinkPreviews) }
    public var recognizeTextInImages: Bool { defaults.bool(forKey: PrefKey.recognizeTextInImages) }
    public var ignoreConfidential: Bool { defaults.bool(forKey: PrefKey.ignoreConfidential) }
    public var ignoreTransient: Bool { defaults.bool(forKey: PrefKey.ignoreTransient) }
    public var ignoreAutoGenerated: Bool { defaults.bool(forKey: PrefKey.ignoreAutoGenerated) }
    public var captureWhileLocked: Bool { defaults.bool(forKey: PrefKey.captureWhileLocked) }
    public var detectSecrets: Bool { defaults.bool(forKey: PrefKey.detectSecrets) }
    public var encryptAtRest: Bool { defaults.bool(forKey: PrefKey.encryptAtRest) }

    public var maxItemBytes: Int {
        let megabytes = defaults.integer(forKey: PrefKey.maxItemMegabytes)
        return max(1, megabytes) * 1_024 * 1_024
    }

    public var ignoredApps: Set<String> {
        Set(defaults.stringArray(forKey: PrefKey.ignoredApps) ?? [])
    }

    public var quickPasteModifier: QuickPasteModifier {
        QuickPasteModifier(rawValue: defaults.string(forKey: PrefKey.quickPasteModifier) ?? "") ?? .command
    }

    public var plainTextModifier: PlainTextModifier {
        PlainTextModifier(rawValue: defaults.string(forKey: PrefKey.plainTextModifier) ?? "") ?? .shift
    }

    /// When capture resumes. `distantFuture` means paused until resumed by hand.
    public var pausedUntil: Date? {
        get {
            let seconds = defaults.double(forKey: PrefKey.pausedUntil)
            guard seconds > 0 else { return nil }
            return Date(timeIntervalSince1970: seconds)
        }
        nonmutating set {
            if let newValue {
                defaults.set(newValue.timeIntervalSince1970, forKey: PrefKey.pausedUntil)
            } else {
                defaults.removeObject(forKey: PrefKey.pausedUntil)
            }
        }
    }

    public func isPaused(at date: Date = Date()) -> Bool {
        guard let pausedUntil else { return false }
        return pausedUntil > date
    }
}
