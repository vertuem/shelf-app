import Foundation

/// Pasteboard type identifiers shared by capture and paste.
///
/// Plain strings so ShelfCore stays free of AppKit; ShelfCapture and
/// ShelfPaste wrap them in `NSPasteboard.PasteboardType`.
public enum PasteboardTypes {
    // nspasteboard.org markers. Password managers set the first; most tools honor all three.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Bundle id of the app that wrote the pasteboard, when the app volunteers it.
    public static let source = "org.nspasteboard.source"
    /// Set by macOS on items that arrived through Universal Clipboard from another device.
    public static let remoteClipboard = "com.apple.is-remote-clipboard"
    /// Older password managers that predate nspasteboard.org.
    public static let legacyConcealed = ["com.agilebits.onepassword", "PasswordPboardType", "de.petermaurer.TransientPasteboardType"]

    public static let plainText = "public.utf8-plain-text"
    public static let utf16PlainText = "public.utf16-external-plain-text"
    public static let legacyString = "NSStringPboardType"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let urlName = "public.url-name"
    public static let fileURL = "public.file-url"
    public static let color = "com.apple.cocoa.pasteboard.color"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"

    /// File promises: the data only exists once the receiver asks for it.
    public static let promisedFileURL = "com.apple.pasteboard.promised-file-url"
    public static let promisedFileContentType = "com.apple.pasteboard.promised-file-content-type"
    public static let promisedSuggestedName = "com.apple.pasteboard.promised-suggested-file-name"
    public static let filePromiseMetadata = "com.apple.NSFilePromiseItemMetaData"

    public static let imageTypes = [png, tiff, jpeg, heic]
    public static let textTypes = [plainText, utf16PlainText, legacyString]
    public static let richTextTypes = [rtf, html, rtfd]

    /// Old-style names the pasteboard server synthesizes from modern types. Storing
    /// them would double every item; writing the modern type brings them back.
    static let legacyAliases: Set = [
        "NSStringPboardType", "NeXT Rich Text Format v1.0 pasteboard type", "NeXT RTFD pasteboard type",
        "NSFilenamesPboardType", "Apple URL pasteboard type", "Apple PDF pasteboard type",
        "NeXT TIFF v4.0 pasteboard type", "Apple PNG pasteboard type", "Apple HTML pasteboard type",
        "Apple files promise pasteboard type", "NeXT font pasteboard type", "NeXT ruler pasteboard type",
        "NSColor pasteboard type",
    ]

    /// True for a synthesized alias of another type on the same item.
    public static func isSynthesizedAlias(_ type: String, itemTypes: Set<String>) -> Bool {
        let hasModernType = itemTypes.contains { $0.hasPrefix("public.") || $0.hasPrefix("com.") }
        guard hasModernType else { return false }
        if legacyAliases.contains(type) || type.hasPrefix("CorePasteboardFlavorType") || type.hasPrefix("NSTypedFilenamesPboardType") {
            return true
        }
        return type == utf16PlainText && itemTypes.contains(plainText)
    }

    public static func isPromise(_ type: String) -> Bool {
        type == promisedFileURL || type == filePromiseMetadata || type.hasPrefix("com.apple.pasteboard.promised-")
    }
}

/// The pseudo source used for Universal Clipboard items. Not a real app.
public enum UniversalClipboardSource {
    public static let bundleID = "com.apple.universal-clipboard"
    public static var name: String { String(localized: "Universal Clipboard") }
}
