import Foundation
import ShelfCore

/// Why a copy was not recorded. Kept for tests and debug logging only; never
/// shown with content.
public enum CaptureRejection: Equatable, Sendable {
    case paused
    /// macOS asks or refuses each time Shelf reads the clipboard (Paste from
    /// Other Apps is not set to Always Allow), so nothing is read.
    case clipboardAccessNotAllowed
    case ownWrite
    case concealed
    case transient
    case autoGenerated
    case ignoredApp(String)
    case screenLocked
    case empty
    case looksLikeSecret
}

/// The filter settings, read once per copy from `Preferences`.
public struct CaptureSettings: Sendable, Equatable {
    public var ignoreConfidential = true
    public var ignoreTransient = true
    public var ignoreAutoGenerated = true
    public var captureWhileLocked = false
    public var detectSecrets = false
    public var ignoredApps: Set<String> = Set(Seeds.ignoredApps)
    public var maxItemBytes = 10 * 1_024 * 1_024

    public init() {}

    public init(_ preferences: Preferences) {
        ignoreConfidential = preferences.ignoreConfidential
        ignoreTransient = preferences.ignoreTransient
        ignoreAutoGenerated = preferences.ignoreAutoGenerated
        captureWhileLocked = preferences.captureWhileLocked
        detectSecrets = preferences.detectSecrets
        ignoredApps = preferences.ignoredApps
        maxItemBytes = preferences.maxItemBytes
    }
}

/// Steps 1 to 5 of the capture flow: decide from the type list alone, before
/// any data is read, whether this copy may be recorded at all.
public enum CaptureFilter {
    public static func evaluate(
        types: Set<String>,
        sourceBundleIDs: [String],
        isScreenLocked: Bool,
        settings: CaptureSettings
    ) -> CaptureRejection? {
        if types.isEmpty { return .empty }
        if types.contains(Brand.originMarkerType) || types.contains(Brand.restoredMarkerType) { return .ownWrite }
        if settings.ignoreConfidential,
           types.contains(PasteboardTypes.concealed) || !types.isDisjoint(with: PasteboardTypes.legacyConcealed) {
            return .concealed
        }
        if settings.ignoreTransient, types.contains(PasteboardTypes.transient) { return .transient }
        if settings.ignoreAutoGenerated, types.contains(PasteboardTypes.autoGenerated) { return .autoGenerated }
        for bundleID in sourceBundleIDs where AppList.matches(bundleID, in: settings.ignoredApps) {
            return .ignoredApp(bundleID)
        }
        if isScreenLocked, !settings.captureWhileLocked { return .screenLocked }
        return nil
    }
}
