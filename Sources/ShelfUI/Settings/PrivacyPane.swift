import ShelfCore
import SwiftUI

struct PrivacyPane: View {
    @AppStorage(PrefKey.showDuringScreenSharing) private var showDuringScreenSharing = false
    @AppStorage(PrefKey.generateLinkPreviews) private var linkPreviews = false
    @AppStorage(PrefKey.recognizeTextInImages) private var recognizeTextInImages = true
    @AppStorage(PrefKey.ignoreConfidential) private var ignoreConfidential = true
    @AppStorage(PrefKey.ignoreTransient) private var ignoreTransient = true
    @AppStorage(PrefKey.ignoreAutoGenerated) private var ignoreAutoGenerated = true
    @AppStorage(PrefKey.detectSecrets) private var detectSecrets = false
    @AppStorage(PrefKey.captureWhileLocked) private var captureWhileLocked = false
    @AppStorage(PrefKey.maxItemMegabytes) private var maxMegabytes = 10
    @AppStorage(PrefKey.encryptAtRest) private var encrypt = true

    var body: some View {
        SettingsForm {
            PaneHeader(pane: .privacy)

            Section {
                SettingToggle(
                    String(localized: "Show during screen sharing"),
                    detail: String(localized: "When off, the shelf and the Paste Stack are invisible to screen sharing, recording and screenshots."),
                    isOn: $showDuringScreenSharing
                )
                Toggle(String(localized: "Generate link previews"), isOn: $linkPreviews)
                if linkPreviews {
                    HStack(alignment: .center, spacing: 12) {
                        IconTile(symbol: "network", color: .orange, size: 28)
                        Footnote(String(localized: "Each copied web link is fetched once to show its title and image. The site sees your IP address, and some one-time links (sign-in, password reset) can be used up by the fetch. Links from ignored apps are never fetched."))
                    }
                }
                SettingToggle(
                    String(localized: "Recognize text in images"),
                    detail: String(localized: "Text in screenshots and photos becomes searchable. Recognition runs on this Mac and nothing leaves it. The text is kept unencrypted in the search index, without anything that looks like a password or key."),
                    isOn: $recognizeTextInImages
                )
            }

            SettingsSection(String(localized: "What is never recorded")) {
                SettingToggle(
                    String(localized: "Ignore confidential content"),
                    detail: String(localized: "Passwords that password managers mark as concealed."),
                    isOn: $ignoreConfidential
                )
                SettingToggle(
                    String(localized: "Ignore transient content"),
                    detail: String(localized: "Temporary data that apps mark as not worth keeping."),
                    isOn: $ignoreTransient
                )
                Toggle(String(localized: "Ignore auto-generated content"), isOn: $ignoreAutoGenerated)
                SettingToggle(
                    String(localized: "Detect secrets"),
                    detail: String(localized: "Skips text that looks like an API key or token: a single word of 20 to 64 random-looking characters. Also skips some harmless strings, such as commit hashes."),
                    isOn: $detectSecrets
                )
                Toggle(String(localized: "Capture while screen is locked"), isOn: $captureWhileLocked)
            }

            SettingsSection(String(localized: "Ignore applications")) {
                AppListEditor(key: PrefKey.ignoredApps, seeds: Seeds.ignoredApps)
            }

            SettingsSection(String(localized: "Storage")) {
                Stepper(value: $maxMegabytes, in: 1...200) {
                    VStack(alignment: .leading, spacing: 2) {
                        LabeledContent(String(localized: "Maximum item size"), value: String(localized: "\(maxMegabytes) MB"))
                        Text(String(localized: "Larger items keep a thumbnail and small metadata only."))
                            .font(.callout)
                            .foregroundStyle(.secondary)
                    }
                }
                SettingToggle(
                    String(localized: "Encrypt history at rest"),
                    detail: String(localized: "Copied data is sealed with a key kept in your login keychain. The search index, which holds the first 500 characters of each text item, stays unencrypted so search stays instant. Turning this off skips sealing for new items."),
                    isOn: $encrypt
                )
            }
        }
    }
}
